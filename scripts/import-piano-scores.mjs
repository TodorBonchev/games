// Build the browser's score data from the checked-in, source-derived MIDI files.
// No network or npm MIDI dependency is needed. See piano/scores/README.md.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = new URL('../piano/scores/', import.meta.url);
const round = value => Math.round(value * 1e9) / 1e9;

export function readMidi(bytes) {
  const b = Buffer.from(bytes);
  if (b.toString('ascii', 0, 4) !== 'MThd') throw new Error('Missing MIDI header');
  const format = b.readUInt16BE(8), count = b.readUInt16BE(10), ppq = b.readUInt16BE(12);
  if (format > 1 || ppq & 0x8000) throw new Error('Only synchronous PPQ MIDI is supported');
  let pos = 8 + b.readUInt32BE(4), duration = 0;
  const tracks = [], signatures = [], tempos = [];
  for (let index = 0; index < count; index++) {
    if (b.toString('ascii', pos, pos + 4) !== 'MTrk') throw new Error('Missing MIDI track');
    const end = pos + 8 + b.readUInt32BE(pos + 4); pos += 8;
    const active = new Map(), notes = []; let tick = 0, status = 0, name = '';
    const variable = () => {
      let v = 0, byte, length = 0;
      do { if (pos >= end || ++length > 4) throw new Error('Invalid MIDI variable length'); byte = b[pos++]; v = v * 128 + (byte & 127); } while (byte & 128);
      return v;
    };
    while (pos < end) {
      tick += variable();
      if (b[pos] & 128) status = b[pos++];
      else if (!status || status >= 0xf0) throw new Error('Invalid MIDI running status');
      if (status === 0xff) {
        const type = b[pos++], length = variable(), data = b.subarray(pos, pos + length); pos += length;
        if (type === 3) name = data.toString();
        if (type === 0x58) signatures.push({ beat: round(tick / ppq), value: [data[0], 2 ** data[1]] });
        if (type === 0x51) tempos.push({ beat: round(tick / ppq), bpm: round(60000000 / data.readUIntBE(0, 3)) });
      } else if (status === 0xf0 || status === 0xf7) { const length = variable(); pos += length; }
      else {
        const kind = status >> 4, channel = status & 15, pitch = b[pos++], velocity = kind === 12 || kind === 13 ? 0 : b[pos++];
        const key = channel + ':' + pitch;
        if (kind === 9 && velocity) {
          const queue = active.get(key) || []; queue.push(tick); active.set(key, queue);
        } else if (kind === 8 || kind === 9) {
          const queue = active.get(key), start = queue?.shift();
          if (start !== undefined && tick > start) notes.push([pitch, round(start / ppq), round((tick - start) / ppq)]);
        }
      }
    }
    if ([...active.values()].some(queue => queue.length)) throw new Error('Unclosed MIDI note in ' + name);
    duration = Math.max(duration, tick / ppq);
    notes.sort((a, c) => a[1] - c[1] || a[0] - c[0] || a[2] - c[2]);
    tracks.push({ name, notes });
  }
  return { tracks, signatures, tempos, duration: round(duration) };
}

export async function buildScores() {
  const manifest = JSON.parse(await readFile(new URL('manifest.json', root), 'utf8'));
  const children = JSON.parse(await readFile(new URL('nursery.json', root), 'utf8'));
  const melodies = JSON.parse(await readFile(new URL('melodies.json', root), 'utf8'));
  const scores = [];
  for (const item of manifest) {
    const bytes = await readFile(new URL(item.midiFile, root)), midi = readMidi(bytes);
    const part = indices => indices.flatMap(index => {
      if (!midi.tracks[index]?.notes.length) throw new Error(item.id + ': empty staff track ' + index);
      return midi.tracks[index].notes;
    }).sort((a, b) => a[1] - b[1] || a[0] - b[0] || a[2] - b[2]);
    scores.push({
      id: item.id, title: item.title, subtitle: item.subtitle, category: item.category, level: item.level,
      score: true, tempo: Math.round(midi.tempos[0]?.bpm || 100), timeSignature: midi.signatures[0]?.value || [4, 4],
      duration: midi.duration, pickup: item.pickup, key: item.key,
      source: { title: 'Mutopia Project', url: item.sourceUrl, scope: item.scope, license: item.license, licenseUrl: item.licenseUrl,
        credit: item.credit, checked: item.checked, sha256: createHash('sha256').update(bytes).digest('hex'),
        file: 'scores/' + item.midiFile, reduction: !!item.reduction, changes: item.changes || 'Repeats unfolded; written durations retained; fixed practice tempo. ' + (item.id === 'brahms' ? 'Vocal and upper piano staff combined in the right hand.' : 'Original staff assignment and pitches retained.') },
      right: part(item.rightTracks), left: part(item.leftTracks),
    });
  }
  scores.push(...children);
  const content = '// Generated by scripts/import-piano-scores.mjs. Sources and licenses: scores/README.md.\nwindow.PIANO_SCORE_DATA = ' + JSON.stringify(scores) + ';\nwindow.PIANO_MELODY_AUDIT = ' + JSON.stringify(melodies) + ';\n';
  await writeFile(new URL('../scores.js', root), content);
  return scores;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const scores = await buildScores();
  console.log('Built ' + scores.length + ' sourced scores (' + scores.reduce((n, s) => n + s.right.length + s.left.length, 0) + ' notes).');
}
